#!/usr/bin/env python3
"""Generate Escape Time's digits, palette, dive targets and menu icon.

Run from the project root (needs Pillow, for the icon):

    python3 tools/build_assets.py

Outputs:
  resources/glyphs/<d>~<tag>.bin   the digits' distance fields (tools/glyphs.py):
  resources/glyphs/s<d>~<tag>.bin  large, and compact for Timeline Quick View
  src/c/generated/glyphs.h         their sizes and stroke weights (GLYPH_L_*, GLYPH_S_*)
  src/c/generated/palette.h        palette and face colors (color) or dither
                                   levels (B&W), from tools/design.py
  src/c/generated/targets.h        the dive targets from tools/design.py, in Q4.27
  resources/images/menu_icon.png   25x25 menu icon: the Mandelbrot set
"""

import math
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import design  # noqa: E402
import glyphs  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GLYPH_DIR = os.path.join(ROOT, "resources", "glyphs")
GENERATED = os.path.join(ROOT, "src", "c", "generated")
ICON = os.path.join(ROOT, "resources", "images", "menu_icon.png")

# Screens by resource tag: (width, height, round, the height the compact
# block must fit in to clear Timeline Quick View).
PLATFORMS = {
    "144w": (144, 168, False, 100),  # aplite, basalt, diorite, flint
    "180w": (180, 180, True, 100),   # chalk
    "200w": (200, 228, False, 190),  # emery
    "260w": (260, 260, True, 178),   # gabbro
}

# Margin to the screen edge (rect) or the circle (round).
MARGIN = 4


def fits(screen_w, screen_h, is_round, block_w, block_h):
    if is_round:
        return math.hypot(block_w / 2, block_h / 2) <= screen_w / 2 - MARGIN
    return block_w <= screen_w - 2 * MARGIN and block_h <= screen_h - 2 * MARGIN


def build_icon():
    # The Mandelbrot set itself, white on black, sampled 4x4 per pixel.
    img = Image.new("1", (25, 25), 0)
    for py in range(25):
        for px in range(25):
            hits = 0
            for sy in range(4):
                for sx in range(4):
                    c = complex(-2.05 + (px + (sx + 0.5) / 4) * 2.6 / 25,
                                1.3 - (py + (sy + 0.5) / 4) * 2.6 / 25)
                    z = 0j
                    for _ in range(60):
                        z = z * z + c
                        if abs(z) > 2:
                            break
                    else:
                        hits += 1
            img.putpixel((px, py), 1 if hits >= 6 else 0)
    img.save(ICON, optimize=True)


def build_palette():
    modes = list(design.MODES)

    def tables(fmt, palettes, faces):
        lines = ["static const uint8_t s_palettes[FACE_MODES][PALETTE_SIZE] = {"]
        lines += ["  {" + ", ".join(fmt(v) for v in p) + "},  // %s" % m
                  for m, p in zip(modes, palettes)]
        lines += ["};", "// Digit, keyline, inside, lace.",
                  "static const uint8_t s_face_colors[FACE_MODES][4] = {"]
        lines += ["  {" + ", ".join(fmt(v) for v in f) + "},  // %s" % m
                  for m, f in zip(modes, faces)]
        return lines + ["};"]

    def argb(c):
        return "0x%02X" % design.argb8(c)

    lines = [
        "// Generated by tools/build_assets.py from tools/design.py. Do not edit.",
        "#pragma once",
        "",
        "#define FPS %d" % design.FPS,
        "#define PALETTE_SIZE %d" % design.PALETTE_SIZE,
        "",
        "// Escape counts further apart than this between neighbours: lace.",
        "#define LACE_STEP %d" % design.LACE_STEP,
        "// Depth: the view's escape counts ranked between these quantiles (percent).",
        "#define DEPTH_LOW_PERCENT %d" % round(100 * design.DEPTH_LOW),
        "#define DEPTH_HIGH_PERCENT %d" % round(100 * design.DEPTH_HIGH),
        "",
        "// The face's looks (the settings page's choices, in this order).",
    ]
    lines += ["#define FACE_MODE_%s %d" % (m.upper(), i) for i, m in enumerate(modes)]
    lines += [
        "#define FACE_MODES %d" % len(modes),
        "",
        "// Per look, the palette (cyclic) and the face's other colors: GColor8 argb",
        "// bytes on color watches, lit pixels out of 16 on B&W ones.",
        "#if defined(PBL_COLOR)",
    ]
    lines += tables(argb, [design.palette(m) for m in modes],
                    [design.face_colors(m) for m in modes])
    lines += ["#else"]
    lines += tables(str, [design.bw_levels(m) for m in modes],
                    [design.bw_face_levels(m) for m in modes])
    lines += ["#endif", ""]
    with open(os.path.join(GENERATED, "palette.h"), "w") as f:
        f.write("\n".join(lines))


def build_targets():
    def fix(d):
        return int(round(d * (1 << 27)))
    lines = [
        "// Generated by tools/build_assets.py from tools/design.py. Do not edit.",
        "#pragma once",
        "",
        "// Dive targets in Q4.27 (real, imaginary): each hour's seed picks one",
        "// (src/c/dive.c), and whether to mirror it.",
        "#define DIVE_TARGETS %d" % len(design.TARGETS),
        "static const int32_t s_targets[DIVE_TARGETS][2] = {",
    ]
    for name, r, i in design.TARGETS:
        lines.append("  {%d, %d},  // %s: %.15f %+.15fi" % (fix(r), fix(i), name, r, i))
    lines += ["};", ""]
    with open(os.path.join(GENERATED, "targets.h"), "w") as f:
        f.write("\n".join(lines))


def build_trig():
    """A quarter wave of sine, 257 entries in Q14 (1.0 is exact), for turning
    the view."""
    values = [round(math.sin(math.pi / 2 * i / 256) * 16384) for i in range(257)]
    lines = [
        "// Generated by tools/build_assets.py. Do not edit.",
        "#pragma once",
        "",
        "// sin(i / 256 of a quarter turn), Q14, i = 0..256.",
        "static const int16_t s_quarter_sine[257] = {",
    ]
    for k in range(0, 257, 12):
        lines.append("  " + ", ".join(str(v) for v in values[k:k + 12]) + ",")
    lines += ["};", ""]
    with open(os.path.join(GENERATED, "trig.h"), "w") as f:
        f.write("\n".join(lines))


def glyph_block(width):
    """(cell height, gap, block width, block height) for digits `width` px
    wide; the block's size includes a mid-weight stroke's ink outside the
    cells."""
    height = round(width * glyphs.GLYPH_ASPECT)
    gap = round(width * glyphs.GAP)
    base, depth, _, _, _, _ = design.style(width)
    ink = 2 * ((2 * base + depth + 7) // 8)  # both sides of a mid-weight stroke
    return height, gap, 2 * width + gap + ink, 2 * height + gap + ink


def largest_glyph(fit):
    width = 8
    while fit(*glyph_block(width + 1)[2:]):
        width += 1
    return width


def build_glyphs():
    """The digits' distance fields and sizes, two sets per screen."""
    os.makedirs(GLYPH_DIR, exist_ok=True)
    lines = [
        "// Generated by tools/build_assets.py from tools/glyphs.py and tools/design.py.",
        "// Do not edit.",
        "#pragma once",
        "",
        "// Digit cells are WIDTH x HEIGHT with GAP between them; a digit's distance",
        "// field is COLS x ROWS samples, 2 px apart, starting PAD px above and left",
        "// of its cell. FIT_H is the height the block needs. STYLE: the FaceStyle.",
    ]
    first = True
    for tag, (screen_w, screen_h, is_round, compact_h) in PLATFORMS.items():
        sets = {
            "L": (largest_glyph(lambda w, h: fits(screen_w, screen_h, is_round, w, h)), ""),
            "S": (largest_glyph(lambda w, h: h <= compact_h and
                                fits(screen_w, screen_h, is_round, w, h)), "s"),
        }
        lines.append("#%s PBL_DISPLAY_WIDTH == %d" % ("if" if first else "elif", screen_w))
        for name, (width, prefix) in sets.items():
            height, gap, _, fit_h = glyph_block(width)
            pad = design.pad(width)
            for d in range(10):
                cols, rows, data = glyphs.distance_field(d, width, pad)
                with open(os.path.join(GLYPH_DIR, "%s%d~%s.bin" % (prefix, d, tag)), "wb") as f:
                    f.write(data)
            print("%s glyphs %s: %dx%d, gap %d, pad %d, field %dx%d"
                  % (tag, name, width, height, gap, pad, cols, rows))
            lines += ["#define GLYPH_%s_%s %d" % (name, key, value) for key, value in (
                ("WIDTH", width), ("HEIGHT", height), ("GAP", gap), ("PAD", pad),
                ("COLS", cols), ("ROWS", rows), ("FIT_H", fit_h))]
            lines.append("#define GLYPH_%s_STYLE {%s}"
                         % (name, ", ".join(str(v) for v in design.style(width))))
        first = False
    lines += ["#else", '#error "No digit metrics for this display width"', "#endif", ""]
    with open(os.path.join(GENERATED, "glyphs.h"), "w") as f:
        f.write("\n".join(lines))


def main():
    os.makedirs(GENERATED, exist_ok=True)
    os.makedirs(os.path.dirname(ICON), exist_ok=True)
    build_icon()
    build_palette()
    build_glyphs()
    build_targets()
    build_trig()
    return 0


if __name__ == "__main__":
    sys.exit(main())
